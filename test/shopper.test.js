const { test } = require('node:test');
const assert = require('node:assert/strict');
const { openDb, createUser } = require('../src/db');
const commerce = require('../src/commerce');
const shopper = require('../src/shopper');
const { createApp } = require('../src/app');
test('Addresses, verified reviews, repeat purchase and support enforce ownership and rollback', async () => {
  const db = openDb(':memory:');
  const alice = createUser(db, { name: 'Alice', username: 'alice', password: 'Password123' });
  const bob = createUser(db, { name: 'Bob', username: 'bob', password: 'Password123' });
  const product = db.data.products[0];
  const address = { id: 'address-1', name: 'Alice', phone: '0901234567', city: 'Hà Nội', ward: 'Test', address: '12 Test', isDefault: true };
  shopper.customer(db, alice.id, '/api/addresses', 'PUT', { items: [address] });
  assert.equal(shopper.customer(db, alice.id, '/api/addresses', 'GET', {}).items.length, 1);
  assert.equal(shopper.customer(db, bob.id, '/api/addresses', 'GET', {}).items.length, 0);
  assert.throws(() => shopper.customer(db, alice.id, '/api/addresses', 'PUT', { items: [address, address] }), /trùng/);
  assert.throws(() => shopper.customer(db, alice.id, `/api/products/${product.id}/reviews`, 'POST', { rating: 5, comment: 'Great' }), /hoàn thành/);
  const order = commerce.createOrder(db, { customer: { name: 'Alice', phone: address.phone, address: '12 Test' }, items: [{ productId: product.id, quantity: 1 }] }, alice.id);
  for (const status of ['confirmed', 'shipping', 'done']) commerce.updateOrderStatus(db, order.id, status);
  const result = shopper.customer(db, alice.id, `/api/products/${product.id}/reviews`, 'POST', { rating: 5, comment: '<script>alert(1)</script>' });
  assert.equal(result.average, 5); assert.equal(result.items[0].verified, true); assert.equal(result.items[0].userId, undefined);
  assert.throws(() => shopper.customer(db, alice.id, `/api/products/${product.id}/reviews`, 'POST', { rating: 4, comment: 'Duplicate' }), /đã đánh giá/);
  shopper.admin(db, '/api/admin/reviews/' + db.data.reviews[0].id, 'PATCH', { hidden: true });
  assert.equal(shopper.reviews(db, product.id).count, 0);
  assert.throws(() => shopper.customer(db, bob.id, `/api/orders/${order.id}/reorder`, 'POST', {}), /Không tìm/);
  product.price += 10000;
  shopper.customer(db, alice.id, `/api/orders/${order.id}/reorder`, 'POST', {});
  assert.equal(db.data.users.find(user => user.id === alice.id).cart[0].quantity, 1);
  const originalCart = structuredClone(db.data.users.find(user => user.id === alice.id).cart);
  const stock = product.stock; product.stock = 0;
  assert.throws(() => shopper.customer(db, alice.id, `/api/orders/${order.id}/reorder`, 'POST', {}), /chỉ còn/);
  assert.deepEqual(db.data.users.find(user => user.id === alice.id).cart, originalCart); product.stock = stock;
  assert.throws(() => shopper.customer(db, bob.id, '/api/support', 'POST', { orderId: order.id, type: 'return', message: 'Return' }), /Không tìm/);
  const ticket = shopper.customer(db, alice.id, '/api/support', 'POST', { orderId: order.id, type: 'return', message: 'Need help' });
  assert.throws(() => shopper.customer(db, alice.id, '/api/support', 'POST', { orderId: order.id, type: 'question', message: 'Duplicate' }), /đang xử lý/);
  shopper.admin(db, '/api/admin/support/' + ticket.id, 'PATCH', { status: 'reviewing', reply: 'We are checking' });
  assert.equal(shopper.customer(db, alice.id, '/api/support', 'GET', {}).items[0].reply, 'We are checking');
  assert.equal(shopper.customer(db, bob.id, '/api/support', 'GET', {}).items.length, 0);
  assert.equal(db.data.orders[0].status, 'done'); assert.equal(product.stock, stock);
  const before = structuredClone(db.data);
  db.save = () => { throw new Error('disk failure'); };
  assert.throws(() => shopper.customer(db, alice.id, '/api/addresses', 'PUT', { items: [] }), /disk failure/);
  assert.deepEqual(db.data, before);
  const server = createApp({ db, adminToken: 'admin-test' });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  try {
    const base = `http://127.0.0.1:${server.address().port}`;
    for (const route of ['/api/addresses', '/api/support', '/api/admin/support', '/api/admin/reviews']) assert.equal((await fetch(base + route)).status, 401);
    assert.equal((await fetch(base + `/api/products/${product.id}/reviews`)).status, 200);
  } finally { const closed = new Promise(resolve => server.close(resolve)); server.closeAllConnections(); server.closeIdleConnections(); await closed; }
});
